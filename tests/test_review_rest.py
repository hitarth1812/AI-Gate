# ------------------------------------------------------------------------------------------------ code.error_check_removed

def removed(res):
    return [(f["path"], f["line"]) for f in res["findings"] if f["rule"] == "code.error_check_removed" and not f["allowed"]]


PY_TRY = ("def load(path):\n    try:\n        return open(path).read()\n    except FileNotFoundError:\n        return None\n"
          "    except PermissionError:\n        raise\n")


def test_python_handler_narrowed_to_a_swallowing_broad_one_is_reported(repo):
    base(repo, {"app/__init__.py": "", "app/io.py": PY_TRY})
    change(repo, {"app/io.py": "def load(path):\n    try:\n        return open(path).read()\n    except Exception:\n        pass\n"})
    f = one(deep(repo), "code.error_check_removed")
    assert f["line"] == 4 and "FileNotFoundError" in f["message"] and f["action"] == "warn"
    assert one(deep(repo, AGENT), "code.error_check_removed")["action"] == "fix"


def test_python_bare_except_replacing_a_specific_one_is_reported(repo):
    base(repo, {"app/__init__.py": "", "app/io.py": PY_TRY})
    change(repo, {"app/io.py": PY_TRY.replace("except FileNotFoundError:\n        return None",
                                              "except:\n        pass")})
    assert removed(deep(repo)) == [("app/io.py", 4)]


def test_python_handler_removed_from_a_function_is_reported(repo):
    base(repo, {"app/__init__.py": "", "app/io.py": PY_TRY})
    change(repo, {"app/io.py": "def load(path):\n    return open(path).read()\n"})
    f = one(deep(repo), "code.error_check_removed")
    assert "handler was removed" in f["message"] and "`load`" in f["message"]


def test_python_handlers_that_stay_or_that_get_logged_are_fine(repo):
    base(repo, {"app/__init__.py": "", "app/io.py": PY_TRY})
    change(repo, {"app/io.py": PY_TRY.replace("return None", "return ''")})
    assert not removed(deep(repo))
    change(repo, {"app/io.py": PY_TRY.replace("except PermissionError:\n        raise",
                                              "except PermissionError as e:\n        raise RuntimeError('no') from e")})
    assert not removed(deep(repo))
    change(repo, {"app/io.py": PY_TRY.replace("except FileNotFoundError:\n        return None",
                                              "except Exception as e:\n        log(e)\n        raise")})
    assert not removed(deep(repo))                                            # broad, but not swallowing


def test_python_deleted_functions_and_text_in_strings_are_not_findings(repo):
    base(repo, {"app/__init__.py": "", "app/io.py": PY_TRY + "\n\nTEXT = 'except Exception: pass'\n"})
    change(repo, {"app/io.py": "TEXT = \"except: pass\"\n# except Exception:\n#     pass\n"})
    assert not removed(deep(repo))


