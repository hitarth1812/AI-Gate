SRC = "def parse_date(text, fmt='%Y'):\n    return text\n"


def review(repo, *args, env=None, fmt="json"):
    proc = repo.run("review", "--offline", "--format", fmt, *args, env=env)
    assert proc.returncode in (0, 1), proc.stderr
    return json.loads(proc.stdout) if fmt == "json" else proc.stdout


# ------------------------------------------------------------------------------------------------ tests.missing_for_change

def test_a_changed_function_without_a_related_test_is_reported(repo):
    base(repo, {"app/__init__.py": "", "app/utils.py": SRC, "tests/test_other.py": "def test_x():\n    assert 1\n"})
    change(repo, {"app/utils.py": SRC.replace("return text", "return text.strip()")})
    f = one(deep(repo), "tests.missing_for_change")
    assert (f["path"], f["line"]) == ("app/utils.py", 1) and "`parse_date`" in f["message"] and f["action"] == "warn"
    assert one(deep(repo, AGENT), "tests.missing_for_change")["action"] == "fix"


@pytest.mark.parametrize("test_path", ["tests/test_utils.py", "tests/unit/test_utils.py", "utils_test.py"])
def test_a_changed_related_python_test_covers_the_change(repo, test_path):
    base(repo, {"app/__init__.py": "", "app/utils.py": SRC, test_path: "def test_x():\n    assert 1\n"})
    change(repo, {"app/utils.py": SRC.replace("return text", "return text.strip()"),
                  test_path: "def test_x():\n    assert 2\n"})
