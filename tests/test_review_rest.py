def test_new_rules_are_documented_and_explainable(repo):
    for rule in ("api.unknown_symbol", "api.bad_call", "api.broken_caller", "tests.missing_for_change", "review.claim_mismatch",
                 "code.error_check_removed"):
        r = aigate.RULES[rule]
        assert r.title and r.hint and r.severity in ("high", "medium", "low") and 0 < r.confidence <= 1
        out = repo.run("explain", rule).stdout
        assert rule in out and "fix:" in out and "[rules]" in out
    assert {aigate.RULES[r].action for r in ("api.unknown_symbol", "api.bad_call", "api.broken_caller",
                                             "tests.missing_for_change", "code.error_check_removed")} == {"fix"}
    assert aigate.RULES["review.claim_mismatch"].action == "warn"


