"""Phase 4A precision: each noisy pattern from the audit run (tests/precision_fixtures.py) is a true-positive or
false-positive case for a human and for an AI agent. An agent's result must never be looser than the gate's was
before Phase 4 (OLD_ACTIONS); only people get the softer treatment."""
import pytest

from conftest import GitRepo, find
import precision_fixtures as fx

RANK = {None: 0, "pass": 1, "warn": 2, "fix": 3, "block": 4}


def line_of(path, needle):
    for i, line in enumerate(fx.FILES[path].split("\n"), 1):
        if needle in line:
            return i
    raise AssertionError(f"{needle!r} is not in {path}")


def actions(res, rule, path, line):
    return sorted({"pass" if f["allowed"] == "info only" else f["action"] for f in res["findings"]
                   if f["rule"] == rule and f["path"] == path and f["line"] == line and (not f["allowed"] or f["allowed"] == "info only")})


@pytest.fixture(scope="module")
def results(tmp_path_factory):
    base = tmp_path_factory.mktemp("precision")
    (base / "repo").mkdir()
    repo = GitRepo(base / "repo", base / "cache")
    repo.write("README.md", "# demo\n")
    repo.commit("init")
    for rel, text in fx.FILES.items():
        p = repo.path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode())
    repo.add()
    return {"human": repo.check("--offline"), "agent": repo.check("--offline", env={"CLAUDECODE": "1"})}


@pytest.mark.parametrize("case", fx.CASES, ids=[c[0] for c in fx.CASES])
def test_case_for_a_human(results, case):
    cid, rule, path, needle, human, _agent = case
    got = actions(results["human"], rule, path, line_of(path, needle))
    assert got == ([human] if human else []), cid


@pytest.mark.parametrize("case", fx.CASES, ids=[c[0] for c in fx.CASES])
def test_case_for_an_agent(results, case):
    cid, rule, path, needle, _human, agent = case
    got = actions(results["agent"], rule, path, line_of(path, needle))
    assert got == ([agent] if agent else []), cid


@pytest.mark.parametrize("case", fx.CASES, ids=[c[0] for c in fx.CASES])
def test_an_agent_is_never_treated_more_leniently_than_before_phase_4(results, case):
    cid, rule, path, needle, _human, _agent = case
    got = actions(results["agent"], rule, path, line_of(path, needle))
    now = max((RANK[a] for a in got), default=0)
    assert now >= RANK[fx.OLD_ACTIONS[cid]] or cid in FALSE_POSITIVES_REMOVED_FOR_EVERYONE, cid


# things that were never credentials, copy-paste or keys: removed for people and agents alike
FALSE_POSITIVES_REMOVED_FOR_EVERYONE = {"label-reset", "label-missing", "label-kebab", "ref-dollar", "ref-double",
                                        "pem-contains", "dup-imports", "dup-sql"}


def test_the_fixture_set_reproduces_every_pattern_the_old_gate_got_wrong(results):
    # at least one case of each item is a finding the old gate raised and the new one does not (for a human)
    softened = [c[0] for c in fx.CASES if RANK[fx.OLD_ACTIONS[c[0]]] > RANK[c[4]]]
    assert len(softened) >= 20


# ------------------------------------------------------------------------------------------------ per item

def stage(repo, files, *args, env=None):
    for path, text in files.items():
        repo.write(path, text)
    repo.add()
    return repo.check("--offline", *args, env=env)


def test_secrets_values_that_are_variable_references_or_labels(repo):
    res = stage(repo, {"app.yaml": 'password: "$DB"\ntoken: "${T}"\nsecret: "$$S"\napi_key: "%K%"\n'
                                   'client_secret: "{{ .Values.s }}"\n'
                                   'access_token: "' + "Zx9kLm2Q" + 'w8vR4tY"\nauth_token: "refresh_token"\n'})
    assert [f["line"] for f in find(res, "secrets.generic")] == [6]


def test_a_private_key_needs_a_body(repo):
    res = stage(repo, {"a.go": 'package a\nvar s = "' + fx.BEGIN + '"\n', "b.pem": fx.BEGIN + "\n" + "\n".join(fx.KEY_LINES) + "\n"})
    assert [f["path"] for f in find(res, "secrets.hardcoded")] == ["b.pem"]


def test_a_key_split_over_string_pieces_is_still_a_key(repo):
    text = 'package a\nvar k = "' + fx.BEGIN + '\\n" +\n\t"' + fx.KEY_LINES[0] + '\\n" +\n\t"' + fx.KEY_LINES[1] + '"\n'
    assert find(stage(repo, {"a.go": text}), "secrets.hardcoded")


def test_generated_files_are_skipped_for_people_but_not_for_agents(repo):
    files = {"x.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n\nfunc big() {\n" + "\tx++\n" * 100 + "}\n"}
    human = stage(repo, files)
    assert not find(human, "size.function_length")
    agent = repo.check("--offline", env={"CLAUDECODE": "1"})
    assert find(agent, "size.function_length")


def test_a_header_added_by_an_agent_does_not_hide_its_placeholder(repo):
    files = {"x.go": "// Code generated by hand. DO NOT EDIT.\npackage x\n\nfunc f() { panic(\"not implemented\") }\n"}
    stage(repo, files)
    assert find(repo.check("--offline", env={"CLAUDECODE": "1"}), "code.placeholder")


def test_secrets_are_still_found_in_generated_files(repo):
    res = stage(repo, {"x.pb.go": "// Code generated. DO NOT EDIT.\npackage x\nconst k = \"" + fx.AWS + "\"\n"})
    assert find(res, "secrets.hardcoded")


def test_duplicate_blocks_ignore_imports_and_short_blocks_for_people_only(repo):
    block = "".join(f"\tv{i} := step({i})\n" for i in range(7))
    files = {"a.go": "package a\n\nfunc a() {\n" + block + "}\n", "b.go": "package a\n\nfunc b() {\n" + block + "}\n"}
    stage(repo, files)
    assert not find(repo.check("--offline"), "code.duplicate_block")
    assert find(repo.check("--offline", env={"CLAUDECODE": "1"}), "code.duplicate_block")


def test_the_duplicate_limit_a_user_sets_is_respected(repo):
    block = "".join(f"\tv{i} := step({i})\n" for i in range(7))
    repo.write(".aigate/lite.toml", "[limits]\nduplicate_lines = 7\n")
    res = stage(repo, {"a.go": "package a\n\nfunc a() {\n" + block + "}\n", "b.go": "package a\n\nfunc b() {\n" + block + "}\n"})
    assert find(res, "code.duplicate_block")


def test_test_files_have_their_own_limits_for_people(repo):
    rows = "".join('\t\t{"c%d", %d},\n' % (i, i) for i in range(90))
    test = "package a\n\nimport \"testing\"\n\nfunc TestT(t *testing.T) {\n\tcases := []struct{ n string; v int }{\n" + rows + "\t}\n\t_ = cases\n}\n"
    stage(repo, {"a_test.go": test})
    assert not find(repo.check("--offline"), "size.function_length")
    assert find(repo.check("--offline", env={"CLAUDECODE": "1"}), "size.function_length")


def test_python_tests_get_the_test_limits_too(repo):
    body = "".join(f"    x{i} = {i}\n" for i in range(90))
    stage(repo, {"test_big.py": "def test_big():\n" + body + "    assert x0 == 0\n"})
    assert not find(repo.check("--offline"), "size.function_length")
    assert find(repo.check("--offline", env={"CLAUDECODE": "1"}), "size.function_length")


def test_limits_tests_is_configurable_and_validated(repo):
    repo.write(".aigate/lite.toml", "[limits.tests]\nfunction_lines = 200\nbogus = 1\ncomplexity = -3\n")
    body = "".join(f"    x{i} = {i}\n" for i in range(150))              # over the default 120, under the configured 200
    res = stage(repo, {"test_big.py": "def test_big():\n" + body + "    assert x0 == 0\n"})
    assert not find(res, "size.function_length")
    msgs = " ".join(f["message"] for f in find(res, "gate.config_invalid"))
    assert "limits.tests.bogus" in msgs and "limits.tests.complexity" in msgs


def test_env_gated_skips_are_warnings_for_people_with_a_hint(repo):
    text = ('package a\n\nimport "testing"\n\nfunc TestA(t *testing.T) {\n\tif os.Getenv("DB") == "" {\n\t\tt.Skip("DB not set")\n\t}\n}\n'
            'func TestB(t *testing.T) {\n\tt.Skip("later")\n}\n')
    res = stage(repo, {"a_test.go": text})
    skips = {f["line"]: f for f in find(res, "tests.skip_added")}
    assert skips[7]["action"] == "warn" and "make CI fail" in skips[7]["hint"]
    assert skips[11]["action"] == "fix"
    agent = repo.check("--offline", env={"CLAUDECODE": "1"})
    assert {f["action"] for f in find(agent, "tests.skip_added")} == {"fix"}


def test_python_skipif_is_environment_gated_and_plain_skip_is_not(repo):
    text = ("import pytest\nimport sys\n\n@pytest.mark.skipif(sys.platform == 'win32', reason='posix only')\ndef test_a():\n    assert 1\n\n"
            "@pytest.mark.skip(reason='later')\ndef test_b():\n    assert 1\n")
    res = stage(repo, {"test_a.py": text})
    by_line = {f["line"]: f["action"] for f in find(res, "tests.skip_added")}
    assert by_line[5] == "warn" and by_line[9] == "fix"


def test_nolint_needs_a_named_linter_and_a_reason(repo):
    nl = "//no" + "lint"
    text = ("package a\n\nfunc f() {\n\t_ = a.Close() " + nl + ":errcheck // best effort\n\t_ = b.Close() " + nl +
            "\n\t_ = c.Close() " + nl + ":errcheck\n\t_ = d.Close() " + nl + ":gosec // fixed input\n}\n")
    res = stage(repo, {"a.go": text})
    lint = {f["line"]: f["action"] for f in find(res, "suppress.lint")}
    assert lint == {4: "warn", 5: "fix", 6: "fix"}
    assert [f["action"] for f in find(res, "suppress.security")] == ["fix"]            # never softened
    assert {f["action"] for f in find(repo.check("--offline", env={"CLAUDECODE": "1"}), "suppress.security")} == {"fix"}


def test_justified_type_ignores_are_warnings_for_people_only(repo):
    ti = "# type: " + "ignore"
    text = f"x: int = 'a'  {ti}[assignment]  # legacy API returns str\ny: int = 'b'  {ti}\nz: int = 'c'  {ti}[assignment]\n"
    res = stage(repo, {"a.py": text})
    assert {f["line"]: f["action"] for f in find(res, "suppress.type")} == {1: "warn", 2: "fix", 3: "fix"}
    assert {f["action"] for f in find(repo.check("--offline", env={"CLAUDECODE": "1"}), "suppress.type")} == {"fix"}


def test_sql_built_from_identifiers_in_a_test_is_a_warning_with_advice(repo):
    res = stage(repo, {"a_test.go": 'package a\n\nfunc TestA() {\n\tdb.Exec("DELETE FROM " + table)\n\tdb.Query("SELECT 1 FROM t WHERE a = " + id)\n}\n',
                       "a.go": 'package a\n\nfunc f() {\n\tdb.Exec("DELETE FROM " + table)\n}\n'})
    got = {(f["path"], f["line"]): f for f in find(res, "security.sql_injection")}
    assert got[("a_test.go", 4)]["action"] == "warn" and "identifier helper" in got[("a_test.go", 4)]["hint"]
    assert got[("a_test.go", 5)]["action"] == "fix" and got[("a.go", 4)]["action"] == "fix"


def test_json_with_extra_data_is_a_syntax_error(repo):
    res = stage(repo, {"out.json": '{"a": 1}\n{"b": 2}\n'})
    assert "Extra data" in find(res, "code.syntax_error")[0]["message"]


def test_a_baseline_entry_keeps_matching_after_a_finding_is_softened(repo):
    # fingerprints do not include the action, so softening a rule never invalidates an adopted baseline
    repo.write("a_test.go", 'package a\n\nimport "testing"\n\nfunc TestA(t *testing.T) {\n\tt.Skip("DB not set")\n}\n')
    repo.commit()
    assert repo.run("baseline").returncode == 0
    repo.commit("baseline")
    found = find(repo.check("--offline", "--all"), "tests.skip_added")
    assert found and all(f["allowed"] == "baseline" for f in found)
