#!/usr/bin/env python3
"""Write eval/TRIAGE_SHEET.md: every REAL training case with its proposed label, for the human to approve (or correct in
eval/LABEL_CHANGES.md) before the labels freeze. The holdout real cases are not listed here (a fixer must not see them);
they follow the same rules and are readable in eval/holdout/.

    py eval/run.py --failures > failures.txt ; py eval/tools/triage_sheet.py failures.txt
"""
import re
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent


def main(failures_file):
    failing = {}
    for ln in Path(failures_file).read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"^(real-[\w-]+)\|(\w+)\|(\w+):(.*)$", ln)
        if m:
            failing.setdefault(m.group(1), []).append(f"{m.group(2)} {m.group(3)} {m.group(4)}")
    rows = []
    for d in sorted((HERE / "corpus").glob("real-*")):
        m = tomllib.loads((d / "case.toml").read_text(encoding="utf-8"))
        origin = m["origin"].split(" (pattern")[0].split(": ", 1)[1]
        if m.get("contested"):
            kind, label = "CONTESTED", "; ".join(f"{s['rule']} {s.get('action')}/{s.get('agent_action')}" for s in m["must_fire"])
        elif m.get("must_not_fire"):
            kind, label = "false positive", "person: no finding" + (" (agent: unlabelled, keeps today's)" if m["who"] == "person" else "")
        else:
            kind = "true positive / by design"
            label = "; ".join(f"{s['rule']} person {s.get('action', '-')} / agent {s.get('agent_action', s.get('action', '-'))}" for s in m["must_fire"])
        now = "matches" if d.name not in failing else "DIFFERS: " + "; ".join(failing[d.name])
        rows.append(f"| `{d.name}` | {origin} | {kind} | {label} | {now} |")
    out = ["# Triage sheet: proposed labels for the REAL cases", "",
           "Generated by `eval/tools/triage_sheet.py` from the corpus and one run of `py eval/run.py --failures` against the",
           "current tool. **These labels are proposals made by the engineer, not by you.** They freeze once you approve them;",
           "reply with the ids you disagree with (or edit `eval/LABEL_CHANGES.md`). Where \"now\" says DIFFERS the tool disagrees",
           "with the proposed label: that is the work the improvement loop will do. Cases marked CONTESTED are excluded from every",
           "metric until you decide.", "",
           "How to read it: `person` / `agent` are the actions the tool should give a person's and an AI agent's change.",
           "An agent is never softer than a person; where the labels give an agent a *lower or equal* action it is today's behaviour.", "",
           "| case | audited location (pattern only; no ATLAS code is stored) | kind | proposed label | tool v0.5.1 now |", "|---|---|---|---|---|", *rows, ""]
    (HERE / "TRIAGE_SHEET.md").write_text("\n".join(out), encoding="utf-8")
    print(f"{len(rows)} real training cases listed")


if __name__ == "__main__":
    main(sys.argv[1])
