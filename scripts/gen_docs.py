#!/usr/bin/env python3
"""Generate docs/RULES.md from aigate_lite.RULES and aigate_lite.PRESETS (never edit that file by hand).

    python scripts/gen_docs.py            # write docs/RULES.md
    python scripts/gen_docs.py --check    # exit 1 if docs/RULES.md is out of date
"""
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "RULES.md")


def load_tool():
    spec = importlib.util.spec_from_file_location("aigate_lite", os.path.join(ROOT, "aigate_lite.py"))
    mod = importlib.util.module_from_spec(spec)
    sys.modules["aigate_lite"] = mod
    spec.loader.exec_module(mod)
    return mod


def presets_table(ag) -> list:
    names = ag.PRESET_NAMES
    rows = []
    for section in ("rules", "gate", "limits"):
        keys = []
        for name in names:
            keys += [k for k in ag.PRESETS[name].get(section, {}) if k not in keys]
        for key in sorted(keys):
            if section == "rules":
                default = ag.RULES[key].action if key in ag.RULES else "(each rule's default)"
                label = f"`{key}`"
            else:
                default = ag.DEFAULT_CONFIG[section][key]
                label = f"`[{section}] {key}`"
            cells = [str(ag.PRESETS[n].get(section, {}).get(key, default)) for n in names]
            rows.append(f"| {label} | " + " | ".join(cells) + " |")
    return ["| setting | " + " | ".join(names) + " |", "|---|" + "---|" * len(names), *rows]


def render(ag) -> str:
    out = ["# Rules and presets", "", "<!-- Generated by scripts/gen_docs.py. Do not edit by hand. -->", "",
           f"aigate-lite: {len(ag.RULES)} rules. Actions: block | fix | warn | off "
           "(block and fix stop the commit). Override any of them in `.aigate/lite.toml` `[rules]`.", "",
           "## Presets", "",
           "`preset = \"relaxed\" | \"balanced\" | \"strict\"` in `.aigate/lite.toml` (default balanced). "
           "Effective config = built-in defaults, then the preset, then your own settings (yours always win). "
           "Only the settings a preset changes are listed; balanced changes nothing.", "",
           *presets_table(ag), "",
           "## Rules", "",
           "| rule | default | severity | what |", "|---|---|---|---|"]
    for rid in sorted(ag.RULES):
        r = ag.RULES[rid]
        out.append(f"| `{rid}` | {r.action} | {r.severity} | {r.title} |")
    return "\n".join(out) + "\n"


def main(argv) -> int:
    text = render(load_tool())
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = ""
        if current != text:
            print("docs/RULES.md is out of date; run: python scripts/gen_docs.py")
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
